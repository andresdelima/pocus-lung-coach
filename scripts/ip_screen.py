"""Intellectual-property screen for everything the app or the repo could expose.

Checks:
1. Verbatim overlap: every run of 7+ consecutive words in a view card that also appears in a source paper.
2. Quoted phrases in the cards (anything in "double quotes" that isn't a coaching line we wrote).
3. Third-party media: any image, video or PDF in files git would publish, or in what the web app serves.
4. Source material stays private: the papers, their extracted text and the notes are gitignored.

Run from the Final Project folder:  .venv/bin/python scripts/ip_screen.py
Exit code 0 = clean, 1 = something to fix.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = sorted((ROOT / "knowledge" / "view_cards").glob("*.md"))
TEXTS = sorted((ROOT / "knowledge" / "literature" / "text").rglob("*.txt"))
N = 7
MEDIA = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".mp4", ".mov", ".avi", ".pdf", ".dcm", ".pptx", ".docx"}
OWN_MEDIA = {"data/samples/",          # synthetic files generated by scripts/make_synthetic_samples.py
             "app/static/reference/",  # simulated reference views drawn by scripts/make_reference_images.py
             "Ultrasound teaching guides/",  # PDFs built from our cards by scripts/make_teaching_guides.py
             "docs/img/",                    # screenshots of our own app and the author's own de-identified clips
             "output/safety_demo/"}          # the author's own clip with our injected test text

# Short technical phrases that are standard terminology, not anyone's expression.
COMMON = {"the pleural line", "lung sliding", "a lines", "b lines"}


def words(text: str) -> list[str]:
    text = re.sub(r"\[[A-Za-z]+\d{2}[^\]]*\]", " ", text)          # drop our citation keys
    return re.findall(r"[a-z0-9]+", text.lower())


def shingles(ws: list[str], n: int) -> set[str]:
    return {" ".join(ws[i:i + n]) for i in range(len(ws) - n + 1)}


def main() -> int:
    problems = 0
    source = {t.stem[:50]: shingles(words(t.read_text(errors="ignore")), N) for t in TEXTS}

    print(f"1. Verbatim overlap ({N}+ word runs) between {len(CARDS)} cards and {len(TEXTS)} source texts")
    for c in CARDS:
        cs = shingles(words(c.read_text()), N)
        for name, ss in source.items():
            hits = sorted(cs & ss)
            if hits:
                problems += 1
                print(f"   ✕ {c.name} ⟷ {name}: {len(hits)} run(s), e.g. '{hits[0]}'")
    if not problems:
        print("   ✓ none")

    print("2. Quoted phrases in cards (excluding 'Coach says' lines, which are our own wording)")
    q = 0
    for c in CARDS:
        for line in c.read_text().splitlines():
            if line.startswith("|"):            # coaching table rows: our own instructions to learners
                continue
            for m in re.findall(r"[\"“]([^\"”]{3,})[\"”]", line):
                q += 1
                print(f"   • {c.name}: \"{m}\"")
    if not q:
        print("   ✓ none")

    print("3. Third-party media in files git would publish or the app serves")
    files = subprocess.run(["git", "ls-files", "--others", "--cached", "--exclude-standard"], cwd=ROOT,
                           capture_output=True, text=True).stdout.splitlines()
    media = [f for f in files if Path(f).suffix.lower() in MEDIA and not any(f.startswith(o) for o in OWN_MEDIA)]
    served = [p for p in (ROOT / "app" / "static").rglob("*") if p.suffix.lower() in MEDIA
              and not any(str(p.relative_to(ROOT)).startswith(o) for o in OWN_MEDIA)]
    for f in media + [str(p.relative_to(ROOT)) for p in served]:
        problems += 1
        print(f"   ✕ {f}")
    if not media and not served:
        print("   ✓ none (only our own generated files: samples, reference images, teaching guides)")

    print("4. Source material kept out of git")
    for path in ["knowledge/literature/x.pdf", "knowledge/literature/text/x.txt", "knowledge/notes/x.md",
                 "instance/keys/master.key"]:
        ok = subprocess.run(["git", "check-ignore", "-q", path], cwd=ROOT).returncode == 0
        problems += 0 if ok else 1
        print(f"   {'✓' if ok else '✕'} {path} ignored")

    print("\nRESULT:", "clean" if problems == 0 else f"{problems} problem(s) to fix")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
